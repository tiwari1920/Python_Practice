# Python Program for comparing strings

s1 = "Python"
s2 = "Python"
s3 = "python"

print("s1 == s2:", s1 == s2)
print("s1 == s3:", s1 == s3)
print("s1 != s3:", s1 != s3)
print("s1 < s3:", s1 < s3)
print("s1 > s3:", s1 > s3)
print("s1 <= s2:", s1 <= s2)
print("s1 >= s2:", s1 >= s2)
print("s1 is s2:", s1 is s2)
print("s1 is not s3:", s1 is not s3)
print("s1.startswith('Py'):", s1.startswith('Py'))
print("s1.endswith('on'):", s1.endswith('on'))
print("s1.find('tho'):", s1.find('tho'))
print("s1.count('o'):", s1.count('o'))
print("s1.upper():", s1.upper())
print("s1.lower():", s1.lower())
print("s1.capitalize():", s1.capitalize())
